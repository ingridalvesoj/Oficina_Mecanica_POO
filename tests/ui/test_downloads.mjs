import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';

const source = await readFile(new URL('../../src/oficina/ui/downloads.js', import.meta.url), 'utf8');
const component = (await import(`data:text/javascript;base64,${Buffer.from(source).toString('base64')}`)).default;
const stored = new Map();
globalThis.sessionStorage = {getItem:key=>stored.get(key), setItem:(key,value)=>stored.set(key,value)};
let clicks=0;
let lastLink;
globalThis.document = {createElement:()=>lastLink={click(){clicks++;},remove(){}}};
const timers=[];
globalThis.setTimeout=callback=>timers.push(callback);
const parentElement={appendChild(){}};
const data={token:'first', content:Buffer.from('%PDF-1.4\n').toString('base64'), filename:'orcamento.pdf'};
component({parentElement,data:{}});
assert.equal(clicks,0);
component({parentElement,data});
assert.equal(clicks,1);
assert.equal(lastLink.download,'orcamento.pdf');
assert.match(lastLink.href,/^blob:/);
component({parentElement,data});
assert.equal(clicks,1);
const remount=(await import(`data:text/javascript;base64,${Buffer.from(source+'\n// remount').toString('base64')}`)).default;
remount({parentElement,data});
assert.equal(clicks,1);
component({parentElement,data:{...data,token:'second'}});
assert.equal(clicks,2);
for(const release of timers) release();
console.log('7 verificações de download automático aprovadas.');
